// Generates src/lib/c9p-1.ts from docs/api/c9p-1.json, the c9p/1 JSON Schema
// that the engine's serde types produce (src-tauri/src/engine/api.rs,
// `schema()`). Run `node scripts/gen-c9p-types.mjs` after the schema changes;
// scripts/test-ipc-contract.mjs fails while the two differ.
//
// It covers only the JSON Schema the engine emits: $ref, const, enum,
// oneOf/anyOf, type lists, objects, maps, arrays, and the `true` schema or one
// with no type at all (a `serde_json::Value` with a doc comment).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
export const SCHEMA_PATH = `${root}docs/api/c9p-1.json`;
export const TYPES_PATH = `${root}src/lib/c9p-1.ts`;

const REF = '#/$defs/';

/** Type name for a `$defs` entry: `HelloParams` → `C9pHelloParams`. */
export const typeName = (def) => (def.startsWith('C9p') ? def : `C9p${def}`);

const literal = (v) => (typeof v === 'string' ? `'${v.replace(/['\\]/g, '\\$&')}'` : JSON.stringify(v));

const key = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : literal(k));

function doc(text, indent) {
  if (!text) return '';
  const lines = text.replace(/\*\//g, '*\\/').split('\n');
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} *${l ? ` ${l}` : ''}`).join('\n')}\n${indent} */\n`;
}

const union = (parts) => [...new Set(parts)].join(' | ');

/** The TS type for a schema, on one line except for inline objects. */
function tsType(s, indent) {
  if (s === true || s === undefined) return 'unknown';
  if (s === false) return 'never';
  if (s.$ref) {
    assert(s.$ref.startsWith(REF), `unsupported $ref ${s.$ref}`);
    return typeName(s.$ref.slice(REF.length));
  }
  if ('const' in s) return literal(s.const);
  if (s.enum) return union(s.enum.map(literal));
  const alts = s.oneOf ?? s.anyOf;
  if (alts) return union(alts.map((a) => tsType(a, indent)));
  if (Array.isArray(s.type)) return union(s.type.map((t) => tsType({ ...s, type: t }, indent)));
  switch (s.type) {
    case undefined:
      return 'unknown';
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      const item = tsType(s.items, indent);
      return /[ |]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    case 'object':
      if (s.properties) return `{\n${members(s, `${indent}  `)}${indent}}`;
      // A map (`HashMap<String, T>`): its values' type.
      if (s.additionalProperties && s.additionalProperties !== true) {
        return `Record<string, ${tsType(s.additionalProperties, indent)}>`;
      }
      return 'Record<string, unknown>';
    default:
      throw new Error(`unsupported schema ${JSON.stringify(s)}`);
  }
}

function members(s, indent) {
  const required = new Set(s.required ?? []);
  return Object.entries(s.properties)
    .map(
      ([k, p]) =>
        `${doc(p.description, indent)}${indent}${key(k)}${required.has(k) ? '' : '?'}: ${tsType(p, indent)};\n`
    )
    .join('');
}

function assert(ok, msg) {
  if (!ok) throw new Error(msg);
}

/** Generate the TS module text for a parsed c9p/1 schema. */
export function generate(schema) {
  const out = [
    '// Generated by scripts/gen-c9p-types.mjs from docs/api/c9p-1.json. Do not edit.',
    '// The engine (src-tauri/src/engine/proto.rs) is the source of truth.',
    '',
    `export const C9P_API_MAJOR = ${schema.apiMajor};`,
    `export const C9P_API_MINOR = ${schema.apiMinor};`,
    '',
  ];
  for (const [name, def] of Object.entries(schema.$defs)) {
    const head = doc(def.description, '');
    if (def.type === 'object' && def.properties) {
      out.push(`${head}export interface ${typeName(name)} {\n${members(def, '  ')}}\n`);
    } else if (def.oneOf?.every((a) => 'const' in a)) {
      // A unit enum: one line per value, with its doc.
      const values = def.oneOf.map((a) => `${doc(a.description, '  ')}  | ${literal(a.const)}`);
      out.push(`${head}export type ${typeName(name)} =\n${values.join('\n')};\n`);
    } else {
      out.push(`${head}export type ${typeName(name)} = ${tsType(def, '')};\n`);
    }
  }
  const table = (entries) =>
    entries
      .map(
        ([name, parts]) =>
          `  ${key(name)}: {\n${Object.entries(parts)
            // `x-stability`, the other markers and notes are not part of the type.
            .filter(([part]) => !part.startsWith('x-') && part !== 'description')
            .map(([part, s]) => `    ${part}: ${tsType(s, '    ')};\n`)
            .join('')}  };\n`
      )
      .join('');
  const frames = Object.entries(schema.frames)
    .map(([k, s]) => `  ${key(k)}: ${tsType(s, '  ')};\n`)
    .join('');
  out.push(`/** The frame types on the engine socket. */\nexport interface C9pFrames {\n${frames}}\n`);
  out.push(
    `/** Each method's params and result (and event frames, for a subscription). */\nexport interface C9pMethods {\n${table(
      Object.entries(schema.methods)
    )}}\n`
  );
  out.push('export type C9pMethod = keyof C9pMethods;\n');
  out.push(
    `/** Each event topic's \`data\`. */\nexport interface C9pTopics {\n${table(
      Object.entries(schema.topics ?? {})
    )}}\n`
  );
  out.push('export type C9pTopic = keyof C9pTopics;\n');
  return out.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, 'utf8'));
  writeFileSync(TYPES_PATH, generate(schema));
  console.log(`wrote ${TYPES_PATH}`);
}
